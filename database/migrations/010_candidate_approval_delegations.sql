CREATE TABLE IF NOT EXISTS candidate_approval_delegations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_id BIGINT UNSIGNED NOT NULL,
    project_id BIGINT UNSIGNED NOT NULL,
    candidate_id BIGINT UNSIGNED NOT NULL,
    manifest_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    gate_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    delegated_by BIGINT UNSIGNED NOT NULL,
    delegated_to BIGINT UNSIGNED NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    closed_at DATETIME(6) NULL,
    closed_reason VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    approval_id BIGINT UNSIGNED NULL,
    active_candidate_id BIGINT UNSIGNED GENERATED ALWAYS AS (IF(closed_at IS NULL, candidate_id, NULL)) STORED,
    UNIQUE KEY candidate_delegation_active (tenant_id, project_id, active_candidate_id),
    UNIQUE KEY candidate_delegation_approval (approval_id),
    KEY candidate_delegation_history (tenant_id, project_id, candidate_id, id),
    FOREIGN KEY (tenant_id, project_id, candidate_id) REFERENCES release_candidates (tenant_id, project_id, id),
    FOREIGN KEY (tenant_id, delegated_by) REFERENCES accounts (tenant_id, id),
    FOREIGN KEY (tenant_id, delegated_to) REFERENCES accounts (tenant_id, id),
    FOREIGN KEY (approval_id) REFERENCES candidate_approvals (id),
    CHECK (delegated_by <> delegated_to),
    CHECK ((closed_at IS NULL) = (closed_reason IS NULL)),
    CHECK ((closed_reason <=> 'approved') = (approval_id IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
